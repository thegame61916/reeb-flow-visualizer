#!/usr/bin/env python3

"""Build a static GitHub Pages bundle for the public Reeb flow viewer.

The output folder is self-contained and can be pushed to a repository named
``reebflowvisualizer.github.io``.  It contains a small landing page with a
dataset selector and one self-contained viewer folder per exported dataset.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any


SCRIPT_DIR = Path(__file__).resolve().parent
STAGE_07_SCRIPT = SCRIPT_DIR / "unified_sankey_viewer" / "stage_07_unified_sankey_viewer.py"
DEFAULT_DATASET_ROOT = Path("/home/mohit/Desktop/postdoc/timeVaryingReebSpace/hpc/datasets")
DEFAULT_DATASETS = ("torus", "MVK_s1", "MVK_s2")
TEXT_FILE_SUFFIXES = {".html", ".css", ".js", ".json", ".md", ".txt"}
LOCAL_PATH_MARKERS = ("/home/mohit", "/Desktop/postdoc", "timeVaryingReebSpace")
PUBLIC_CSS_VERSION = "pages-adaptive-v1"


@dataclass(frozen=True)
class DatasetSpec:
    dataset_id: str
    label: str
    base_dir: Path
    include_fiber_surfaces: bool = True


def parse_dataset_spec(raw: str, dataset_root: Path) -> DatasetSpec:
    """Parse NAME or NAME=/path entries."""

    if "=" in raw:
        name, path_text = raw.split("=", 1)
        dataset_id = name.strip()
        base_dir = Path(path_text).expanduser().resolve()
    else:
        dataset_id = raw.strip()
        base_dir = (dataset_root / dataset_id).resolve()
    if not dataset_id:
        raise ValueError(f"Invalid dataset spec: {raw!r}")
    return DatasetSpec(
        dataset_id=dataset_id,
        label=dataset_id.replace("_", " "),
        base_dir=base_dir,
        include_fiber_surfaces=dataset_id.lower() != "torus",
    )


def run_stage_07(base_dir: Path) -> None:
    if not STAGE_07_SCRIPT.exists():
        raise FileNotFoundError(f"Cannot find Stage 7 script: {STAGE_07_SCRIPT}")
    subprocess.run(
        [sys.executable, str(STAGE_07_SCRIPT), "--base-dir", str(base_dir)],
        cwd=SCRIPT_DIR,
        check=True,
    )


def viewer_dir_for(base_dir: Path) -> Path:
    return base_dir / "sankey" / "unified_sankey_viewer"


def safe_reset_output_dir(output_dir: Path, *, force: bool) -> None:
    marker = output_dir / ".reebflow_pages_export"
    if output_dir.exists():
        if not force and not marker.exists():
            raise FileExistsError(
                f"{output_dir} already exists and does not look like a previous export. "
                "Use --force to overwrite it."
            )
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    marker.write_text("generated by build_github_pages_site.py\n", encoding="utf-8")


def scrub_path_value(key: str, value: str, dataset: DatasetSpec) -> str:
    if not any(marker in value for marker in LOCAL_PATH_MARKERS):
        return value
    key = key.lower()
    if key in {"base_dir"}:
        return dataset.dataset_id
    if key in {"sheet_image_dir"}:
        return "sheet_images"
    if key in {"fiber_surface_image_dir"}:
        return "fiber_surface_images" if dataset.include_fiber_surfaces else ""
    if key in {"presets"}:
        return "paper_exports/presets"
    if key in {"images"}:
        return "paper_exports/images"
    if key in {"matches"}:
        return "compareSheetShapesCache/results/sheet_shape_matches.json"
    if key in {"overlap"}:
        return "sankey/sheet_overlaps.json"
    if key.endswith("_file") or key in {"rsi_file", "rsijson_file"}:
        return Path(value).name
    return Path(value).name


def scrub_data_for_public_site(obj: Any, dataset: DatasetSpec, parent_key: str = "") -> Any:
    if isinstance(obj, dict):
        cleaned = {
            key: scrub_data_for_public_site(value, dataset, key)
            for key, value in obj.items()
        }
        if parent_key == "":
            meta = cleaned.setdefault("meta", {})
            if isinstance(meta, dict):
                meta["dataset_id"] = dataset.dataset_id
                meta["dataset_name"] = dataset.label
                meta["base_dir"] = dataset.dataset_id
                meta["sheet_image_dir"] = "sheet_images"
                meta["fiber_surface_image_dir"] = (
                    "fiber_surface_images" if dataset.include_fiber_surfaces else ""
                )
                meta["public_export"] = True
        return cleaned
    if isinstance(obj, list):
        return [scrub_data_for_public_site(value, dataset, parent_key) for value in obj]
    if isinstance(obj, str):
        return scrub_path_value(parent_key, obj, dataset)
    return obj


def remove_fiber_surface_references(obj: Any) -> Any:
    if isinstance(obj, dict):
        return {
            key: (None if key == "fiber_surface_image" else remove_fiber_surface_references(value))
            for key, value in obj.items()
        }
    if isinstance(obj, list):
        return [remove_fiber_surface_references(value) for value in obj]
    return obj


def collect_media_references(data: dict[str, Any], *, include_fiber_surfaces: bool) -> set[str]:
    refs: set[str] = set()

    def walk(obj: Any) -> None:
        if isinstance(obj, dict):
            thumbnail = obj.get("thumbnail")
            if isinstance(thumbnail, str) and thumbnail:
                refs.add(thumbnail)
            fiber = obj.get("fiber_surface_image")
            if include_fiber_surfaces and isinstance(fiber, str) and fiber:
                refs.add(fiber)
            for value in obj.values():
                walk(value)
        elif isinstance(obj, list):
            for value in obj:
                walk(value)

    walk(data)
    return refs


def copy_file(src: Path, dst: Path) -> int:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return dst.stat().st_size


def copy_referenced_media(viewer_dir: Path, dataset_dir: Path, refs: set[str]) -> tuple[int, int]:
    count = 0
    total_bytes = 0
    missing: list[str] = []
    for ref in sorted(refs):
        if ref.startswith("/") or ".." in Path(ref).parts:
            missing.append(ref)
            continue
        src = viewer_dir / ref
        if not src.exists():
            missing.append(ref)
            continue
        total_bytes += copy_file(src, dataset_dir / ref)
        count += 1
    if missing:
        preview = ", ".join(missing[:8])
        suffix = "" if len(missing) <= 8 else f", ... ({len(missing)} missing)"
        print(f"Warning: missing media in {viewer_dir}: {preview}{suffix}", file=sys.stderr)
    return count, total_bytes


def assert_no_local_paths(path: Path) -> None:
    for file_path in path.rglob("*"):
        if not file_path.is_file() or file_path.suffix.lower() not in TEXT_FILE_SUFFIXES:
            continue
        text = file_path.read_text(encoding="utf-8", errors="ignore")
        for marker in LOCAL_PATH_MARKERS:
            if marker in text:
                raise RuntimeError(f"Local path marker {marker!r} remains in {file_path}")


def largest_files(path: Path, limit: int = 8) -> list[tuple[int, Path]]:
    files = [(file_path.stat().st_size, file_path) for file_path in path.rglob("*") if file_path.is_file()]
    files.sort(reverse=True)
    return files[:limit]


def human_size(num_bytes: int) -> str:
    value = float(num_bytes)
    for unit in ("B", "KiB", "MiB", "GiB"):
        if value < 1024 or unit == "GiB":
            return f"{value:.1f} {unit}" if unit != "B" else f"{int(value)} B"
        value /= 1024
    return f"{num_bytes} B"


