def public_dataset_selector_markup(manifest: list[dict[str, Any]], current_id: str) -> str:
    options = "\n".join(
        f'          <option value="{item["id"]}"{" selected" if item["id"] == current_id else ""}>{item["label"]}</option>'
        for item in manifest
    )
    return f"""<div class="dataset-switcher">
        <label>
          Dataset
          <select id="datasetSelect">
{options}
          </select>
        </label>
      </div>"""


def public_dataset_selector_script(manifest: list[dict[str, Any]], current_id: str) -> str:
    manifest_json = json.dumps([
        {"id": item["id"], "label": item["label"]}
        for item in manifest
    ], separators=(",", ":"))
    return f"""  <script>
    (() => {{
      const DATASETS = {manifest_json};
      const CURRENT_DATASET = {json.dumps(current_id)};
      const select = document.getElementById("datasetSelect");
      if (!select) return;
      select.addEventListener("change", () => {{
        const dataset = DATASETS.find(item => item.id === select.value);
        if (!dataset || dataset.id === CURRENT_DATASET) return;
        window.location.href = `../${{dataset.id}}/index.html`;
      }});
    }})();
  </script>
"""


def inject_dataset_selector(dataset_dir: Path, manifest: list[dict[str, Any]], current_id: str) -> None:
    index_path = dataset_dir / "index.html"
    style_path = dataset_dir / "style.css"
    html = index_path.read_text(encoding="utf-8")
    selector = public_dataset_selector_markup(manifest, current_id)
    script = public_dataset_selector_script(manifest, current_id)

    html = re.sub(
        r'href="style\.css(?:\?v=[^"]*)?"',
        f'href="style.css?v={PUBLIC_CSS_VERSION}"',
        html,
        count=1,
    )
    html = html.replace("<body>", '<body class="public-page">', 1)
    html = html.replace("<header>", '<header class="public-header">', 1)
    html = re.sub(
        r"(<div class=\"title-block\">.*?</div>)",
        f"\\1\n      {selector}",
        html,
        count=1,
        flags=re.S,
    )
    html = html.replace("</body>", script + "</body>", 1)
    index_path.write_text(html, encoding="utf-8")

    public_css = """

/* Public GitHub Pages dataset selector. */
body.public-page header.public-header {
  position: relative;
}
body.public-page .dataset-switcher {
  left: 50%;
  position: absolute;
  top: 50%;
  transform: translate(-50%, -50%);
}
body.public-page .dataset-switcher label {
  display: inline-flex;
  align-items: center;
  gap: 8px;
  margin: 0;
  font-size: 13px;
  color: #111827;
}
body.public-page .dataset-switcher select {
  height: 30px;
  min-width: 110px;
}
"""
    style_path.write_text(style_path.read_text(encoding="utf-8") + public_css, encoding="utf-8")


def inject_dataset_selectors(output_dir: Path, manifest: list[dict[str, Any]]) -> None:
    for item in manifest:
        inject_dataset_selector(output_dir / "datasets" / item["id"], manifest, item["id"])


def copy_dataset_viewer(dataset: DatasetSpec, output_dir: Path) -> dict[str, Any]:
    viewer_dir = viewer_dir_for(dataset.base_dir)
    if not viewer_dir.exists():
        raise FileNotFoundError(f"Viewer has not been built for {dataset.dataset_id}: {viewer_dir}")

    dataset_dir = output_dir / "datasets" / dataset.dataset_id
    dataset_dir.mkdir(parents=True, exist_ok=True)

    for name in ("index.html", "viewer.js", "viewer_common.js", "style.css"):
        copy_file(viewer_dir / name, dataset_dir / name)

    data = json.loads((viewer_dir / "data.json").read_text(encoding="utf-8"))
    if not dataset.include_fiber_surfaces:
        data = remove_fiber_surface_references(data)
    data = scrub_data_for_public_site(data, dataset)
    media_refs = collect_media_references(
        data,
        include_fiber_surfaces=dataset.include_fiber_surfaces,
    )
    media_count, media_bytes = copy_referenced_media(viewer_dir, dataset_dir, media_refs)

    data_path = dataset_dir / "data.json"
    data_path.write_text(json.dumps(data, separators=(",", ":")), encoding="utf-8")

    total_bytes = sum(file_path.stat().st_size for file_path in dataset_dir.rglob("*") if file_path.is_file())
    return {
        "id": dataset.dataset_id,
        "label": dataset.label,
        "path": f"datasets/{dataset.dataset_id}/index.html",
        "timesteps": data.get("meta", {}).get("timesteps"),
        "media_files": media_count,
        "media_size_bytes": media_bytes,
        "dataset_size_bytes": total_bytes,
        "includes_fiber_surfaces": dataset.include_fiber_surfaces,
    }


def write_readme(output_dir: Path, manifest: list[dict[str, Any]]) -> None:
    lines = [
        "# Reeb Flow Visualizer",
        "",
        "Datasets can be changed from `torus`, `MVK_s1`, and `MVK_s2` using the dropdown above.",
    ]
    (output_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


def warn_about_large_files(output_dir: Path) -> None:
    for size, file_path in largest_files(output_dir):
        if size >= 50 * 1024 * 1024:
            print(f"Warning: large file {human_size(size)} {file_path.relative_to(output_dir)}")
        if size >= 100 * 1024 * 1024:
            raise RuntimeError(
                f"GitHub blocks files over 100 MiB: {file_path} is {human_size(size)}"
            )


def build_site(args: argparse.Namespace) -> None:
    dataset_root = args.dataset_root.expanduser().resolve()
    dataset_args = args.dataset if args.dataset else list(DEFAULT_DATASETS)
    datasets = [parse_dataset_spec(raw, dataset_root) for raw in dataset_args]
    output_dir = args.output_dir.expanduser().resolve()

    for dataset in datasets:
        if not dataset.base_dir.exists():
            raise FileNotFoundError(f"Dataset not found: {dataset.base_dir}")

    safe_reset_output_dir(output_dir, force=args.force)
    (output_dir / ".nojekyll").write_text("", encoding="utf-8")

    manifest: list[dict[str, Any]] = []
    for dataset in datasets:
        if not args.skip_viewer_rebuild:
            print(f"Building viewer assets for {dataset.dataset_id}...")
            run_stage_07(dataset.base_dir)
        print(f"Copying {dataset.dataset_id}...")
        manifest.append(copy_dataset_viewer(dataset, output_dir))

    inject_dataset_selectors(output_dir, manifest)
    write_dataset_loader_index(output_dir, manifest)
    write_readme(output_dir, manifest)
    assert_no_local_paths(output_dir)
    warn_about_large_files(output_dir)

    total_bytes = sum(file_path.stat().st_size for file_path in output_dir.rglob("*") if file_path.is_file())
    print(f"\nWrote {output_dir}")
    print(f"Total export size: {human_size(total_bytes)}")
    for item in manifest:
        print(
            f"  {item['id']}: {human_size(int(item['dataset_size_bytes']))}, "
            f"{item['media_files']} media files"
        )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build a self-contained GitHub Pages site for the Reeb flow visualizer."
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=SCRIPT_DIR / "github_pages_site",
        help="Output folder to create. Default: ./github_pages_site",
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=DEFAULT_DATASET_ROOT,
        help=f"Dataset root. Default: {DEFAULT_DATASET_ROOT}",
    )
    parser.add_argument(
        "--dataset",
        action="append",
        default=None,
        help=(
            "Dataset to export, as NAME or NAME=/absolute/path. "
            "May be repeated. Default: torus, MVK_s1, MVK_s2."
        ),
    )
    parser.add_argument(
        "--skip-viewer-rebuild",
        action="store_true",
        help="Copy existing unified viewer folders instead of rebuilding Stage 7 first.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing output folder even if it does not contain the export marker.",
    )
    args = parser.parse_args()
    build_site(args)


if __name__ == "__main__":
    main()
